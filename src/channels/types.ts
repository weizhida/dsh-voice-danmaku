/**
 * 弹幕发送通道接口。
 *
 * 这是整个项目里**最可能被替换的部分**："往哪发"取决于平台，而平台会变。
 * 所以它被隔离成一个 provider：
 *   * B 站 HTTP 接口（当前实现）；
 *   * 未来：页面内注入（用你自己登录的浏览器页面发，请求完全"原生"）；
 *   * 未来：其他平台。
 *
 * 新增一个通道不需要碰原生层，也不需要碰状态机。
 */

/** 发送结果。 */
export interface SendResult {
  /** 是否成功。`unsure` 为真时这一项没有意义 —— 上层必须先看 `unsure`。 */
  ok: boolean;
  /**
   * **结果未知**：请求可能已经发出去了，但我们没拿到确认。
   *
   * 它既不是成功也不是失败，必须单独处理 —— 这个区分有实际后果：
   *
   *   * 当成**失败**：用户重试 → 弹幕发了两条。而"同一句话短时间发两遍"
   *     恰恰是最像机器人的特征，是真正会招来风控的行为。
   *   * 当成**成功**：真没发出去时用户不知道（但他看直播间会发现，代价小得多）。
   *
   * 所以上层（状态机）收到它时**必须进入锁定态**，在结果明确之前不接受任何
   * 输入 —— 而不是显示一句"可能已经发出去了，别急着重按"让用户自己去判断。
   */
  unsure?: boolean;
  /** 成功时的补充信息（如"已发送"）。 */
  detail?: string;
  /** 失败时的可读原因。 */
  error?: string;
}

/** 发送通道。 */
export interface DanmakuChannel {
  /** 通道标识，出现在日志与设置里。 */
  readonly id: string;
  /**
   * 发送前自检：配置是否齐全、凭证是否够用。
   * 返回问题描述数组，空数组表示可以发。
   * 刻意不抛异常 —— "还没配好"是要展示给用户的状态，不是程序错误。
   */
  check(): Promise<string[]>;
  /**
   * 发送一条弹幕。
   *
   * **实现必须自己执行频率限制**（最小间隔 + 每小时上限），不要依赖调用方。
   * 风控风险属于通道实现的责任范围：不同平台的上限完全不同，
   * 把它放在状态机里既不知道平台的规矩，也没法按平台调整。
   *
   * @throws 网络失败或其他不可恢复错误时抛出；业务性拒绝请返回 `ok: false`。
   */
  send(text: string): Promise<SendResult>;
}
